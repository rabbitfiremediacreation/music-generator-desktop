export const yue2Text = (language: string) => language === "de" ? de : en;

export function yue2ErrorText(message: string, language: string): string {
  const t = yue2Text(language);
  return message.startsWith("yue2_") && Object.hasOwn(t, message) ? t[message as keyof typeof t] : message;
}
